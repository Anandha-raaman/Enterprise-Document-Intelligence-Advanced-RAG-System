import re
import json
import requests
from typing import Generator, List, Dict, Any, Optional
from app.config import Config

class RAGGenerator:
    """
    Enterprise RAG inference generator supporting both synchronous completion
    and real-time token streaming via Ollama and fallback backends.
    """

    SYSTEM_PROMPT_TEMPLATE = """You are an Enterprise Document Intelligence AI Assistant.
Answer the question accurately, concisely, and strictly based on the provided reference documentation.

MANDATORY RULES:
1. CITATION: Cite [REF-1], [REF-2], etc., for every fact, figure, or requirement mentioned.
2. TOPIC RELEVANCE: Answer ONLY what is specifically asked in QUESTION. Do NOT summarize or list unrelated policies, benefits, or sections from the references that do not directly answer the user's question.
3. CONCISE & FACTUAL: State the specific facts, numbers, days, and requirements directly, then stop.
4. ADMISSIBILITY: If the question cannot be answered from the provided references, state: "Based on the provided documentation, this information is not specified."

REFERENCE DOCUMENTATION:
{context_block}
"""

    def __init__(
        self,
        provider: str = Config.LLM_PROVIDER,
        base_url: str = Config.OLLAMA_BASE_URL,
        primary_model: str = Config.OLLAMA_PRIMARY_MODEL,
        fallback_model: str = Config.OLLAMA_FALLBACK_MODEL
    ):
        self.provider = provider
        self.base_url = base_url.rstrip("/")
        self.primary_model = primary_model
        self.fallback_model = fallback_model

    @staticmethod
    def clean_repetitions(text: str) -> str:
        """
        Deduplicates repetitive looping lines or phrases generated by small models.
        """
        if not text:
            return ""

        lines = text.split("\n")
        seen_lines = set()
        cleaned_lines = []
        consecutive_repeats = 0

        for line in lines:
            line_str = line.strip()
            # If line is identical to immediately preceding line, skip
            if line_str and cleaned_lines and line_str == cleaned_lines[-1].strip():
                continue

            # If long bullet line repeated more than once overall
            if len(line_str) > 25 and line_str in seen_lines:
                consecutive_repeats += 1
                if consecutive_repeats >= 2:
                    break  # Cut off runaway looping
                continue

            consecutive_repeats = 0
            if line_str:
                seen_lines.add(line_str)
            cleaned_lines.append(line)

        result = "\n".join(cleaned_lines).strip()

        # Deduplicate inline repeating patterns
        pattern = re.compile(r"(\*\s+[^*]{20,}\s+)(\1{2,})")
        result = pattern.sub(r"\1", result)

        return result

    def _build_chat_messages(
        self,
        query: str,
        context_block: str,
        history: Optional[List[Dict[str, Any]]] = None
    ) -> List[Dict[str, str]]:
        """Construct structured chat messages adhering to Ollama /api/chat format."""
        system_instructions = (
            "You are an enterprise document Q&A assistant. "
            "Answer the user question directly, factually, and concisely using ONLY the provided documentation. "
            "Cite [REF-1], [REF-2] for specific figures, rules, or requirements mentioned. "
            "If the question cannot be answered from the documentation, reply: 'Based on the provided documentation, this information is not specified.'"
        )

        messages = [{"role": "system", "content": system_instructions}]

        if history:
            for h in history[-2:]:
                if h.get("user"):
                    messages.append({"role": "user", "content": h["user"]})
                if h.get("assistant"):
                    messages.append({"role": "assistant", "content": h["assistant"]})

        user_content = (
            f"DOCUMENTATION:\n{context_block}\n\n"
            f"QUESTION: {query}\n\n"
            f"Answer ONLY the current QUESTION based strictly on the DOCUMENTATION above. Do not repeat previous answers:"
        )
        messages.append({"role": "user", "content": user_content})
        return messages

    def _build_full_prompt(
        self,
        query: str,
        context_block: str,
        history: Optional[List[Dict[str, Any]]] = None
    ) -> str:
        """Construct prompt combining system instructions, prior conversation, and user query."""
        system_section = self.SYSTEM_PROMPT_TEMPLATE.format(context_block=context_block)
        
        history_text = ""
        if history:
            history_lines = []
            for h in history[-3:]:
                history_lines.append(f"User: {h.get('user', '')}")
                history_lines.append(f"Assistant: {h.get('assistant', '')}")
            history_text = "PRIOR CONVERSATION HISTORY:\n" + "\n".join(history_lines) + "\n\n"

        prompt = (
            f"{system_section}\n\n"
            f"{history_text}"
            f"QUESTION: {query}\n\n"
            f"GROUNDED ANSWER:"
        )
        return prompt

    def generate(
        self,
        query: str,
        context_block: str,
        history: Optional[List[Dict[str, Any]]] = None
    ) -> str:
        """Synchronous response generation using Ollama /api/chat with fallback."""
        if not context_block or "No relevant context found" in context_block:
            return "Based on the provided documentation, this information is not specified."

        timeout_sec = getattr(Config, "LLM_REQUEST_TIMEOUT", 30)
        messages = self._build_chat_messages(query, context_block, history)
        prompt = self._build_full_prompt(query, context_block, history)

        for model in [self.primary_model, self.fallback_model]:
            # Step 1: Try structured /api/chat endpoint (best for chat templates and instruction following)
            try:
                chat_url = f"{self.base_url}/api/chat"
                chat_payload = {
                    "model": model,
                    "messages": messages,
                    "stream": False,
                    "options": {
                        "temperature": Config.LLM_TEMPERATURE,
                        "num_predict": Config.LLM_MAX_TOKENS,
                        "repeat_penalty": 1.25,
                        "stop": ["QUESTION:", "USER:", "REFERENCE DOCUMENTATION:"]
                    }
                }
                resp = requests.post(chat_url, json=chat_payload, timeout=timeout_sec)
                if resp.status_code == 200:
                    data = resp.json()
                    answer = data.get("message", {}).get("content", "").strip()
                    if answer:
                        return self.clean_repetitions(answer)
            except Exception as e:
                print(f"[Generator] Ollama chat model '{model}' call failed: {e}")

            # Step 2: Fallback to /api/generate endpoint if /api/chat not supported
            try:
                gen_url = f"{self.base_url}/api/generate"
                gen_payload = {
                    "model": model,
                    "prompt": prompt,
                    "stream": False,
                    "options": {
                        "temperature": Config.LLM_TEMPERATURE,
                        "num_predict": Config.LLM_MAX_TOKENS,
                        "repeat_penalty": 1.25,
                        "stop": ["QUESTION:", "PRIOR CONVERSATION", "USER:", "\n\n\n\n", "REFERENCE DOCUMENTATION:"]
                    }
                }
                resp = requests.post(gen_url, json=gen_payload, timeout=timeout_sec)
                if resp.status_code == 200:
                    data = resp.json()
                    answer = data.get("response", "").strip()
                    if answer:
                        return self.clean_repetitions(answer)
            except Exception as e:
                print(f"[Generator] Ollama generate model '{model}' call failed: {e}")

        # Fallback heuristic extractor if Ollama server is unreachable
        return self._heuristic_fallback_answer(query, context_block)

    def stream_generate(
        self,
        query: str,
        context_block: str,
        history: Optional[List[Dict[str, Any]]] = None
    ) -> Generator[str, None, None]:
        """Real-time token streaming generator for Server-Sent Events (SSE)."""
        if not context_block or "No relevant context found" in context_block:
            fallback_text = "Based on the provided documentation, this information is not specified."
            for w in fallback_text.split(" "):
                yield w + " "
            return

        timeout_sec = getattr(Config, "LLM_REQUEST_TIMEOUT", 30)
        messages = self._build_chat_messages(query, context_block, history)
        prompt = self._build_full_prompt(query, context_block, history)

        stream_success = False
        for model in [self.primary_model, self.fallback_model]:
            # Try /api/chat streaming first
            try:
                chat_url = f"{self.base_url}/api/chat"
                chat_payload = {
                    "model": model,
                    "messages": messages,
                    "stream": True,
                    "options": {
                        "temperature": Config.LLM_TEMPERATURE,
                        "num_predict": Config.LLM_MAX_TOKENS,
                        "repeat_penalty": 1.25,
                        "stop": ["QUESTION:", "USER:", "REFERENCE DOCUMENTATION:"]
                    }
                }
                resp = requests.post(chat_url, json=chat_payload, stream=True, timeout=timeout_sec)
                if resp.status_code == 200:
                    recent_tokens: List[str] = []
                    repeat_count = 0
                    for line in resp.iter_lines():
                        if line:
                            data = json.loads(line.decode("utf-8"))
                            token = data.get("message", {}).get("content", "")
                            if token:
                                if len(recent_tokens) > 10 and "".join(recent_tokens[-6:]) == "".join(recent_tokens[-12:-6]):
                                    repeat_count += 1
                                    if repeat_count > 2:
                                        break
                                recent_tokens.append(token)
                                yield token
                            if data.get("done", False):
                                break
                    stream_success = True
                    break
            except Exception as e:
                print(f"[Generator Stream] Model '{model}' chat stream failed: {e}")

            # Fallback to /api/generate streaming
            try:
                gen_url = f"{self.base_url}/api/generate"
                gen_payload = {
                    "model": model,
                    "prompt": prompt,
                    "stream": True,
                    "options": {
                        "temperature": Config.LLM_TEMPERATURE,
                        "num_predict": Config.LLM_MAX_TOKENS,
                        "repeat_penalty": 1.25,
                        "stop": ["QUESTION:", "PRIOR CONVERSATION", "USER:", "\n\n\n\n", "REFERENCE DOCUMENTATION:"]
                    }
                }
                resp = requests.post(gen_url, json=gen_payload, stream=True, timeout=timeout_sec)
                if resp.status_code == 200:
                    recent_tokens: List[str] = []
                    repeat_count = 0
                    for line in resp.iter_lines():
                        if line:
                            data = json.loads(line.decode("utf-8"))
                            token = data.get("response", "")
                            if token:
                                if len(recent_tokens) > 10 and "".join(recent_tokens[-6:]) == "".join(recent_tokens[-12:-6]):
                                    repeat_count += 1
                                    if repeat_count > 2:
                                        break
                                recent_tokens.append(token)
                                yield token
                            if data.get("done", False):
                                break
                    stream_success = True
                    break
            except Exception as e:
                print(f"[Generator Stream] Model '{model}' generate stream failed: {e}")

        if not stream_success:
            # Yield fallback response token by token
            fallback_text = self._heuristic_fallback_answer(query, context_block)
            words = fallback_text.split(" ")
            for w in words:
                yield w + " "

    def _heuristic_fallback_answer(self, query: str, context_block: str) -> str:
        """Deterministic extractor providing grounded answer if LLM engine is offline."""
        if not context_block or "No relevant context found" in context_block:
            return "Based on the provided documentation, this information is not specified."

        # Extract first reference excerpt from context
        match = re.search(r"(\[REF-1\][^\n]*\n(?:[^\n]*\n){1,6})", context_block)
        if match:
            return (
                f"Based on the enterprise documentation [REF-1], here is the relevant excerpt regarding '{query}':\n\n"
                f"{match.group(1).strip()}"
            )

        return "Based on the provided documentation, this information is not specified."
